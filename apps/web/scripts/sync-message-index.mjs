// Regenerates src/i18n/messages.ts from messages/en/*.json. Run after adding a message file:
//   node scripts/sync-message-index.mjs
import { readdirSync, writeFileSync } from 'node:fs';

const names = readdirSync(new URL('../messages/en/', import.meta.url))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -5))
  .sort();
const missing = names.filter((n) => !readdirSync(new URL('../messages/ar/', import.meta.url)).includes(`${n}.json`));
if (missing.length) {
  console.error(`Missing Arabic files: ${missing.join(', ')}`);
  process.exit(1);
}
writeFileSync(
  new URL('../src/i18n/messages.ts', import.meta.url),
  `// Generated by scripts/sync-message-index.mjs. One entry per messages/<locale>/<name>.json.\nexport const messageFiles = ${JSON.stringify(names, null, 2)} as const;\n`,
);
console.log(`${names.length} message files`);
